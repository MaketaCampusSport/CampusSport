import { Column, CreateDateColumn, Entity, PrimaryGeneratedColumn } from 'typeorm';
import type { AccountStatus, Role } from '../enums';

export interface NotificationPreferencesValue {
  push: boolean;
  email: boolean;
  sms: boolean;
  language: 'ro' | 'en';
}

@Entity({ name: 'users' })
export class User {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ name: 'full_name', type: 'text' })
  fullName: string;

  @Column({ type: 'text' })
  email: string;

  @Column({ type: 'text', nullable: true })
  phone: string | null;

  @Column({ type: 'text' })
  role: Role;

  @Column({ type: 'text', default: 'active' })
  status: AccountStatus;

  @Column({ name: 'suspended_until', type: 'timestamptz', nullable: true })
  suspendedUntil: Date | null;

  @Column({ name: 'sso_subject', type: 'text', nullable: true })
  ssoSubject: string | null;

  @Column({ name: 'email_verified_at', type: 'timestamptz', nullable: true })
  emailVerifiedAt: Date | null;

  @Column({ name: 'phone_verified_at', type: 'timestamptz', nullable: true })
  phoneVerifiedAt: Date | null;

  /** Only loaded on demand (`addSelect`), never serialized. */
  @Column({ name: 'totp_secret', type: 'text', nullable: true, select: false })
  totpSecret?: string | null;

  /** Generated by the database default. */
  @Column({ name: 'calendar_token', type: 'uuid', insert: false })
  calendarToken: string;

  @Column({ name: 'notification_preferences', type: 'jsonb', insert: false })
  notificationPreferences: NotificationPreferencesValue;

  @Column({ name: 'last_active_at', type: 'timestamptz', nullable: true })
  lastActiveAt: Date | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;
}
